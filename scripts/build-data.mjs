// Generates the static data the app ships with: teams (with conference), active players and
// head coaches, all from ESPN's public JSON. Run before launch (and again on lock day if rosters
// moved): `npm run data`. Output goes to src/data/*.json and is committed.
import { writeFile, mkdir } from 'node:fs/promises'

const SEASON = 2027 // ESPN labels the 2026-27 season by its ending year
// ESPN rejects some bot user agents (e.g. "Claude-User"), so present as a plain browser.
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36'

// ESPN abbreviations differ from the NBA tricodes people know.
const TRICODE = { NY: 'NYK', GS: 'GSW', SA: 'SAS', NO: 'NOP', UTAH: 'UTA', WSH: 'WAS' }

async function getJson(url) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { 'user-agent': UA, accept: 'application/json' } })
    if (res.ok) return res.json()
    if (attempt >= 3) throw new Error(`${res.status} ${url}`)
    await new Promise((r) => setTimeout(r, 1000 * attempt))
  }
}

const standings = await getJson(
  `https://site.api.espn.com/apis/v2/sports/basketball/nba/standings?season=${SEASON}&seasontype=2`,
)
const teamsMeta = await getJson('https://site.api.espn.com/apis/site/v2/sports/basketball/nba/teams')
const metaById = new Map(
  teamsMeta.sports[0].leagues[0].teams.map(({ team }) => [team.id, team]),
)

const teams = []
for (const conf of standings.children) {
  const conference = conf.abbreviation === 'East' ? 'E' : 'W'
  for (const entry of conf.standings.entries) {
    const t = entry.team
    const meta = metaById.get(t.id) ?? {}
    teams.push({
      espnId: t.id,
      abbr: TRICODE[t.abbreviation] ?? t.abbreviation,
      espnAbbr: t.abbreviation,
      name: t.displayName,
      shortName: t.shortDisplayName,
      conference,
      color: meta.color ? `#${meta.color}` : '#333333',
      altColor: meta.alternateColor ? `#${meta.alternateColor}` : '#999999',
      logo: `https://a.espncdn.com/i/teamlogos/nba/500/${t.abbreviation.toLowerCase()}.png`,
    })
  }
}
if (teams.length !== 30) throw new Error(`expected 30 teams, got ${teams.length}`)
teams.sort((a, b) => a.name.localeCompare(b.name))

const players = []
const coaches = []
for (const team of teams) {
  const roster = await getJson(
    `https://site.api.espn.com/apis/site/v2/sports/basketball/nba/teams/${team.espnId}/roster`,
  )
  for (const a of roster.athletes ?? []) {
    if (a.status?.type && a.status.type !== 'active') continue
    players.push({
      id: a.id,
      name: a.displayName,
      team: team.abbr,
      pos: a.position?.abbreviation ?? '',
      exp: a.experience?.years ?? null,
      // ESPN reports 0 years of experience for players who have not made their NBA debut.
      rookie: (a.experience?.years ?? 0) === 0,
      headshot: a.headshot?.href ?? null,
    })
  }
  for (const c of roster.coach ?? []) {
    coaches.push({ id: c.id, name: `${c.firstName} ${c.lastName}`, team: team.abbr })
  }
}
players.sort((a, b) => a.name.localeCompare(b.name))
coaches.sort((a, b) => a.name.localeCompare(b.name))

await mkdir(new URL('../src/data/', import.meta.url), { recursive: true })
const out = (file, data) =>
  writeFile(new URL(`../src/data/${file}`, import.meta.url), JSON.stringify(data, null, 1) + '\n')
// Teams are emitted as a TS module so pure modules (and `node --test`) can import them.
await writeFile(
  new URL('../src/data/teams.ts', import.meta.url),
  [
    '// Generated by scripts/build-data.mjs — do not edit by hand.',
    "import type { Team } from '../lib/types.ts'",
    '',
    `export const TEAMS: readonly Team[] = ${JSON.stringify(teams, null, 1)}`,
    '',
  ].join('\n'),
)
await out('players.json', { generatedAt: new Date().toISOString(), players })
await out('coaches.json', { generatedAt: new Date().toISOString(), coaches })

console.log(
  `teams ${teams.length} (E ${teams.filter((t) => t.conference === 'E').length}), ` +
    `players ${players.length} (rookies ${players.filter((p) => p.rookie).length}), coaches ${coaches.length}`,
)
